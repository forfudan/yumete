/// Where a key stands in the table: a letter of either case, `;`, or `' '`
/// for Space.
fn place(key: char) -> Option<usize> {
    match key {
        ' ' => Some(27),
        ';' => Some(26),
        c if c.is_ascii_alphabetic() => KEYS.find(c.to_ascii_lowercase()),
        _ => None,
    }
}

/// **The 當量 of striking `first` then `second`**; `None` for a pair the
/// table does not have. Space is `' '`.
pub fn of(first: char, second: char) -> Option<f64> {
    let tenths = TENTHS[place(first)?][place(second)?];
    (tenths > 0).then(|| tenths as f64 / 10.0)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_reads_as_the_study_gives_it() {
        assert_eq!(of('a', 'a'), Some(1.3));
        assert_eq!(of('a', 'k'), Some(1.0));
        assert_eq!(of(' ', 'a'), Some(1.4));
        assert_eq!(of('y', ' '), Some(1.3));
        assert_eq!(of(';', ';'), Some(1.4));
        assert_eq!(of('q', 'c'), Some(2.1));
        assert_eq!(of('Y', ' '), of('y', ' '));
        assert_eq!(of(' ', ' '), None);
        assert_eq!(of('a', '1'), None);
        assert_eq!(of('_', 'a'), None);
        let keys: Vec<char> = KEYS.replace('_', " ").chars().collect();
        let given: Vec<f64> = keys.iter().flat_map(|&a| keys.iter().filter_map(move |&b| of(a, b))).collect();
        assert_eq!(given.len(), 783);
        assert!(given.iter().all(|v| (1.0..=2.1).contains(v)));
    }
}
